import type { SolarDatasetFile } from '../types';

const fmtKm = (km: number) => (km >= 1e6 ? `${(km / 1e6).toFixed(2)}e6` : km >= 1000 ? Math.round(km).toLocaleString('en-US') : km.toFixed(1));
const fmtAs = (a: number) => (a >= 3600 ? `${(a / 3600).toFixed(2)}°` : a >= 60 ? `${(a / 60).toFixed(1)}′` : `${a.toFixed(1)}″`);

/** Markdown table of the measured model error against JPL Horizons. */
export function renderSolarValidationMarkdown(file: SolarDatasetFile): string {
  const m = file.manifest;
  const rows = m.validation;
  const lines: string[] = [
    '# Solar System model validation',
    '',
    `Generated by \`npx tsx tools/solar-import.ts\` (built ${m.builtAt}). Do not edit by hand.`,
    '',
    `Each row compares Atlas's position for a body with **JPL Horizons** at the same instant (TDB), in the ICRF equatorial frame. Reference epoch of the dataset: ${m.referenceEpoch.iso} (JD ${m.referenceEpoch.jdTdb.toFixed(6)} TDB).`,
    'Error is the straight-line distance between the two positions. Angular error is that distance as seen from the Sun (planets) or the parent planet (satellites).',
    '',
  ];
  const planets = [...new Set(rows.filter((r) => file.bodies.find((b) => b.id === r.body)?.kind === 'planet').map((r) => r.body))];
  const planetDates = [...new Set(rows.filter((r) => planets.includes(r.body)).map((r) => r.label))];
  lines.push('## Planets (JPL low-accuracy Keplerian elements, valid 1800 to 2050)', '', `| Planet | ${planetDates.join(' | ')} |`, `|---|${planetDates.map(() => '---:').join('|')}|`);
  for (const p of planets) {
    const cells = planetDates.map((d) => { const r = rows.find((x) => x.body === p && x.label === d); return r ? `${fmtKm(r.errorKm)} km (${fmtAs(r.errorArcsec)})` : '-'; });
    lines.push(`| ${p} | ${cells.join(' | ')} |`);
  }
  const moons = [...new Set(rows.filter((r) => file.bodies.find((b) => b.id === r.body)?.kind === 'moon').map((r) => r.body))];
  const moonLabels = [...new Set(rows.filter((r) => moons.includes(r.body)).map((r) => r.label))];
  lines.push('', '## Satellites (osculating elements at the epoch, advanced at a mean-longitude rate fitted to Horizons)', '', 'Errors are relative to the satellite’s distance from its planet (the satellite would be shown this far, as a fraction of its orbit, from where JPL puts it).', '', `| Satellite | ${moonLabels.join(' | ')} |`, `|---|${moonLabels.map(() => '---:').join('|')}|`);
  for (const mo of moons) {
    const cells = moonLabels.map((d) => { const r = rows.find((x) => x.body === mo && x.label === d); return r ? `${(r.relativeError * 100).toFixed(1)}%` : '-'; });
    lines.push(`| ${mo} | ${cells.join(' | ')} |`);
  }
  lines.push('', '## Notes', '', ...m.notes.map((n) => `- ${n}`), '');
  return lines.join('\n');
}
