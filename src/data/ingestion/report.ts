import type { GaiaManifest, SimbadManifest } from '../catalogue/types';
import type { QualityReport } from './quality';

const n = (x: number): string => x.toLocaleString('en-US');
const pct = (x: number, of: number): string => (of > 0 ? ` (${((100 * x) / of).toFixed(1)}%)` : '');

export function renderQualityMarkdown(q: QualityReport, gaia: GaiaManifest, simbad?: SimbadManifest): string {
  const total = q.counts.imported;
  const lines: string[] = [
    '# Dataset quality report',
    '',
    `Generated by \`npm run data:import\` from \`${gaia.id}\` v${gaia.version} (built ${gaia.builtAt}). Do not edit by hand.`,
    '',
    '## Import counts',
    '',
    '| Measure | Count |',
    '|---|---:|',
    `| Rows returned by the Gaia query | ${n(q.counts.queryRows)} |`,
    `| Records imported | ${n(q.counts.imported)} |`,
    `| Records rejected (invalid) | ${n(q.counts.rejected)} |`,
    '',
  ];
  if (q.counts.rejected > 0) {
    lines.push('Rejections by reason (a record can have several):', '', '| Reason | Records |', '|---|---:|');
    for (const [k, v] of Object.entries(q.counts.rejectedByReason)) lines.push(`| ${k} | ${n(v)} |`);
    lines.push('');
  } else {
    lines.push('No records were rejected: every returned row passed the hard validation rules (valid source id, finite coordinates in range, plausible G magnitude when present, non-negative uncertainties, reference epoch J2016.0). The full rejected list, when non-empty, is in the JSON report.', '');
  }
  lines.push(
    '## Distance reliability',
    '',
    'Distance is inferred only from parallax (see `docs/SCIENTIFIC_DATA.md`). A missing or unreliable parallax gives NO distance; it is never treated as zero.',
    '',
    '| Class | Records |',
    '|---|---:|',
    `| Reliable (parallax/error >= ${gaia.thresholds.reliableParallaxSnr}) | ${n(q.distance.reliable)}${pct(q.distance.reliable, total)} |`,
    `| Marginal (${gaia.thresholds.marginalParallaxSnr} to ${gaia.thresholds.reliableParallaxSnr}) | ${n(q.distance.marginal)}${pct(q.distance.marginal, total)} |`,
    `| Unreliable (< ${gaia.thresholds.marginalParallaxSnr} or parallax <= 0): no distance | ${n(q.distance.unreliable)}${pct(q.distance.unreliable, total)} |`,
    `| Invalid (parallax present, uncertainty missing): no distance | ${n(q.distance.invalid)} |`,
    `| Missing (no parallax in catalogue): no distance | ${n(q.distance.missing)}${pct(q.distance.missing, total)} |`,
    `| **Placed in 3D** | **${n(q.distance.placedIn3d)}** |`,
    `| Not placed in 3D | ${n(q.distance.notPlacedIn3d)} |`,
    `| **Drawn** (placed in 3D and has a G magnitude) | **${n(q.distance.drawable)}** |`,
    '',
    '## Missing values',
    '',
    '| Quantity | Records without it |',
    '|---|---:|',
    `| Parallax | ${n(q.missingValues.parallax)} |`,
    `| Proper motion | ${n(q.missingValues.properMotion)} |`,
    `| BP and/or RP photometry | ${n(q.missingValues.bpRp)} |`,
    `| GSP-Phot Teff (modelled) | ${n(q.missingValues.teffGspphot)}${pct(q.missingValues.teffGspphot, total)} |`,
    '',
    '## Quality flags (records are kept and flagged, not dropped)',
    '',
    '| Flag | Records |',
    '|---|---:|',
  );
  for (const [k, v] of Object.entries(q.flags)) lines.push(`| ${k} | ${n(v)} |`);
  lines.push(
    '',
    '## Cross-identification and duplicates',
    '',
    '| Measure | Count |',
    '|---|---:|',
    `| Gaia sources with a Hipparcos cross-match | ${n(q.crossIdentification.hipparcosMatched)} |`,
    `| Hipparcos numbers claimed by more than one Gaia source (groups) | ${n(q.crossIdentification.hipparcosConflictGroups)} |`,
    `| Gaia sources involved in those conflicts | ${n(q.crossIdentification.hipparcosConflictSources)} |`,
    `| Positional duplicate candidates (< 0.5 arcsec, reported not merged) | ${n(q.crossIdentification.positionalDuplicateCandidates)} |`,
  );
  if (q.crossIdentification.simbad) {
    const s = q.crossIdentification.simbad;
    lines.push(
      `| SIMBAD: Gaia ids requested | ${n(s.requested)} |`,
      `| SIMBAD: matched (exact identifier) | ${n(s.matched)}${pct(s.matched, s.requested)} |`,
      `| SIMBAD: unmatched (no SIMBAD object has this Gaia id) | ${n(s.unmatched)} |`,
      `| SIMBAD: Gaia ids with conflicting SIMBAD objects (left unidentified; matched + unmatched + conflicts = requested) | ${n(s.conflicts)} |`,
      `| SIMBAD: objects matched by more than one Gaia source | ${n(s.sharedObjects)} |`,
    );
  } else {
    lines.push('| SIMBAD cross-identification | not run |');
  }
  if (simbad) lines.push('', `SIMBAD service used: ${simbad.service.name} (${simbad.service.endpoint}). ${simbad.service.note}`);
  if (q.notes.length) lines.push('', '## Notes', '', ...q.notes.map((x) => `- ${x}`));
  lines.push('');
  return lines.join('\n');
}

export function renderProvenanceMarkdown(gaia: GaiaManifest, simbad?: SimbadManifest): string {
  const lines: string[] = [
    '# Data provenance report',
    '',
    'Generated by `npm run data:import`. Do not edit by hand.',
    '',
    '## Gaia DR3 subset',
    '',
    '| Item | Value |',
    '|---|---|',
    `| Dataset | \`${gaia.id}\` v${gaia.version} |`,
    `| Catalogue | ${gaia.catalogue.name} (release ${gaia.catalogue.release}, ${gaia.catalogue.releaseDate}) |`,
    `| Archive | ${gaia.catalogue.archive} |`,
    `| TAP endpoint | ${gaia.retrieval.endpoint} |`,
    `| Documentation | ${gaia.catalogue.documentation} |`,
    `| Reference frame and epoch | ${gaia.catalogue.referenceFrame}, J${gaia.catalogue.referenceEpoch.toFixed(1)} |`,
    `| Retrieved | ${gaia.retrieval.retrievedAt} |`,
    `| Raw download | ${n(gaia.retrieval.rawBytes)} bytes, ${n(gaia.retrieval.rawRows)} rows, SHA-256 \`${gaia.retrieval.rawSha256}\` |`,
    `| Dataset content SHA-256 | \`${gaia.contentSha256}\` |`,
    `| Built | ${gaia.builtAt} |`,
    '',
    '### Selection criteria',
    '',
    ...gaia.selection.map((s) => `- ${s}`),
    '',
    '### ADQL submitted',
    '',
    '```sql',
    gaia.retrieval.adql,
    '```',
    '',
    '### Attribution',
    '',
    ...gaia.attribution.map((s) => `- ${s}`),
    '',
  ];
  if (simbad) {
    lines.push(
      '## SIMBAD cross-identification',
      '',
      '| Item | Value |',
      '|---|---|',
      `| Dataset | \`${simbad.id}\` v${simbad.version} |`,
      `| Service | ${simbad.service.name} |`,
      `| Endpoint | ${simbad.service.endpoint} |`,
      `| Service note | ${simbad.service.note} |`,
      `| Retrieved | ${simbad.retrievedAt} |`,
      `| Requested / matched / unmatched / conflicts | ${n(simbad.requested)} / ${n(simbad.matched)} / ${n(simbad.unmatched)} / ${n(simbad.conflicts)} |`,
      '',
      '### Query shape (one batch shown; ids are chunked)',
      '',
      '```sql',
      simbad.batchQuery,
      '```',
      '',
      '### Attribution',
      '',
      ...simbad.attribution.map((s) => `- ${s}`),
      '',
    );
  } else lines.push('## SIMBAD cross-identification', '', 'Not run for this build.', '');
  return lines.join('\n');
}
